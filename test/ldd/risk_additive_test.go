// A migration file is high risk unless it is clearly additive (T164, L1422,
// L1423): when its text holds only recognisable additive operations (SQL
// CREATE TABLE, CREATE INDEX, ADD COLUMN that is nullable or has a default;
// Rails create_table, add_column, add_index, add_reference; Django
// CreateModel, AddField, AddIndex; Alembic op.create_table, op.add_column,
// op.create_index) it is medium, "migration (additive)". Anything else, a
// file that cannot be read, or one with no operation stays high, "migration
// or schema". Only the up/upgrade part of a file with a down part is judged.
// Other reasons still apply, and other files keep their risk.
package ldd

import (
	"os"
	"path/filepath"
	"regexp"
	"testing"

	"github.com/jachavarro2004/jhon-agent/test/support"
)

// riskOfMigration is jhon risk, as JSON and as text, on a repository whose
// change is file (with the test touched): the tier and file's reason line.
func riskOfMigration(t *testing.T, file, text string) (string, string, string) {
	t.Helper()
	root := riskRepo(t)
	put(t, root, file, text)
	put(t, root, "test/app.test.ts", touched)
	r := risk(t, root)
	line := ""
	for _, x := range r.Reasons {
		if x.File == file {
			line = x.Level + " " + x.File + ": " + x.Why
		}
	}
	h := jhonGit(t, root, "risk")
	equal(t, h.Code, 0, h.Stderr)
	return r.Tier, line, h.Stdout
}

