func TestRiskAdditiveMigrationIsNotHigh(t *testing.T) {
	t.Parallel()
	for _, c := range additiveMigrations {
		t.Run(c.file, func(t *testing.T) {
			t.Parallel()
			tier, line, text := riskOfMigration(t, c.file, c.text)
			equal(t, line, "medium "+c.file+": migration (additive)")
			equal(t, tier, "medium", line)
			match(t, text, `(?m)^risk: medium \(base HEAD\)$`)
			match(t, text, `(?m)^  medium +`+regexp.QuoteMeta(c.file)+`: migration \(additive\)$`)
		})
	}
}

